//
// The past-customer badge (20261123210000) on real PostgreSQL (PGlite),
// applied TWICE because apply_all_post_merge.sql re-runs every migration.
//
// What this proves:
//   A  the customer lookup: lifetime totals come from the customer's whole
//      history even when the refresh window is narrow, cancelled orders are
//      excluded, a re-run changes nothing, and coverage is recorded
//   B  the scores are Blake's: email ~0.95, exact name + handle 0.7-0.8,
//      exact name alone ~0.5 reduced by namesakes, surname- or first-name-only
//      does not flag, a brand or channel name says "can't match"
//   C  an order older than 24 months is a weaker signal, and a company whose
//      own history is shorter than 24 months has every score capped and said
//   D  one company's customers never match another company's prospects
//   E  neither function is callable by a browser role, and a human
//      'confirmed' is never overwritten
//   F  Blake's own hand pass of 2026-11-23 reproduces: the exact-name creator
//      is flagged, the two surname-only ones are not, the channel names
//      cannot match
//
// Mutations (CI runs each and requires the suite to FAIL):
//   PASTCUST_MUTATION=rls         RLS left off the lookup table
//   PASTCUST_MUTATION=company     the lookup's select policy drops the company filter
//   PASTCUST_MUTATION=funcgrant   the matcher stays callable by the browser
//   PASTCUST_MUTATION=surname     a single-token (surname-only) name is matched
//   PASTCUST_MUTATION=brand       a brand or channel name is matched like a person
//   PASTCUST_MUTATION=namesake    a name shared by many customers keeps the full score
//   PASTCUST_MUTATION=stale       an order older than 24 months scores the same
//   PASTCUST_MUTATION=shorthist   a short order history does not cap the score
//   PASTCUST_MUTATION=crossco     the matcher reads another company's customers
//   PASTCUST_MUTATION=confirmed   a human 'confirmed' is overwritten by a re-run
//   PASTCUST_MUTATION=cancelled   cancelled orders count toward the customer's totals
//   PASTCUST_MUTATION=window      the refresh totals only the window, not the history
//   PASTCUST_MUTATION=idxpred     the orders index predicate stops matching the refresh
//   PASTCUST_MUTATION=anonread    anon keeps Supabase's default read of the lookup
//   PASTCUST_MUTATION=clientwrite a browser role keeps Supabase's default write of the lookup
//   PASTCUST_MUTATION=wholescan   the refresh aggregates the whole order history again
//   PASTCUST_MUTATION=nopred      the per-customer history pass drops the partial index's predicate

