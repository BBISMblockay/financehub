// scripts/tests/customer-consent-step-database.test.mjs
//
// The batched consent rollup (20261125010000) on real PostgreSQL (PGlite),
// applied TWICE because apply_all_post_merge.sql re-runs every migration.
//
// What this proves:
//   A  stepping through a company in small batches gives exactly the same
//      profile consent as the one-statement refresh it replaces
//   B  the cursor resumes where the last step stopped, a pass ends with
//      pass_done and the next step starts a new pass from the beginning
//   C  a profile whose email has no customer record loses its copied consent
//   D  one company's step never touches another company's profiles
//   E  no browser role can call it
//
// Mutations (each must make the suite FAIL):
//   STEP_MUTATION=nocursor   the cursor is never stored (every step restarts)
//   STEP_MUTATION=noclear    orphaned consent is left behind
//   STEP_MUTATION=grant      the step stays callable by the browser
//   STEP_MUTATION=nocompany  the update drops the company filter
//
// Run: node scripts/tests/customer-consent-step-database.test.mjs

import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from './finance-db/node_modules/@electric-sql/pglite/dist/index.js';

const MUT = process.env.STEP_MUTATION || '';
const db = new PGlite();
const CO_A = '11111111-1111-1111-1111-111111111111';
const CO_B = '22222222-2222-2222-2222-222222222222';

await db.exec(`
create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create table auth.users(id uuid primary key);
create table entities(id uuid primary key);
create function active_company_id() returns uuid language sql as
  $$ select nullif(current_setting('test.company', true), '')::uuid $$;
create function stamp_company_entity_id() returns trigger language plpgsql as
  $$ begin return new; end $$;
create function attach_stamp_company_entity_id_triggers() returns void language sql as $$ select $$;
create function refresh_chat_schema_catalog() returns void language sql as $$ select $$;
create table shopify_connections(id uuid primary key default gen_random_uuid());
create table sync_jobs(id bigint generated by default as identity primary key,
  company_entity_id uuid, connection_id uuid, job_type text not null,
  status text not null default 'running', result jsonb);
create table company_customer_profiles(
  id uuid primary key default gen_random_uuid(),
  company_entity_id uuid not null references entities(id) on delete cascade,
  customer_key text not null, customer_id text, email_lc text,
  name_lc text, order_count integer not null default 0,
  lifetime_spend numeric not null default 0,
  updated_at timestamptz not null default now(),
  unique (company_entity_id, customer_key));
create table company_customer_profile_state (
  company_entity_id uuid primary key references entities(id) on delete cascade,
  covered_from timestamptz, last_refreshed_at timestamptz,
  customers integer not null default 0);
insert into entities(id) values ('${CO_A}'), ('${CO_B}');
grant all on all tables in schema public to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated;
`);

const base = await readFile(new URL('../../supabase/migrations/20261124020000_shopify_customer_marketing_consent.sql', import.meta.url), 'utf8');
let step = await readFile(new URL('../../supabase/migrations/20261125010000_customer_consent_batched_rollup.sql', import.meta.url), 'utf8');
if (MUT === 'nocursor') step = step.replace('set consent_cursor       = case when v_done then null else v_last end', 'set consent_cursor       = null');
if (MUT === 'noclear') step = step.replace('and (p.email_consent_state is not null or p.sms_consent_state is not null)', 'and false');
if (MUT === 'grant') step = step.replace(/revoke all on function public\.refresh_company_customer_consent_step[^;]*;/, '');
if (MUT === 'nocompany') step = step.replace("    update public.company_customer_profiles p\n       set email_consent_state = src.email_consent_state,", "    update public.company_customer_profiles p\n       set email_consent_state = src.email_consent_state,").replace('     where p.company_entity_id = p_company\n       and p.email_lc = src.email_lc', '     where p.email_lc = src.email_lc');

await db.exec(base); await db.exec(base);
await db.exec(step); await db.exec(step);

// Seven profiles in A (one orphan with stale consent, one without email), one
// shared email in B. Customers: two stores for one email (measured beats a
// later unmeasured edit).
await db.exec(`
insert into company_customer_profiles(company_entity_id, customer_key, email_lc, email_consent_state, sms_consent_state) values
 ('${CO_A}','e:a@x','a@x',null,null), ('${CO_A}','e:b@x','b@x',null,null), ('${CO_A}','e:c@x','c@x',null,null),
 ('${CO_A}','e:d@x','d@x',null,null), ('${CO_A}','e:e@x','e@x',null,null),
 ('${CO_A}','e:gone@x','gone@x','subscribed',null), ('${CO_A}','cid:9',null,null,null),
 ('${CO_B}','e:a@x','a@x',null,null);
insert into shopify_customers(company_entity_id, shop_domain, customer_id, email, email_consent_state, email_consent_updated_at, shopify_updated_at) values
 ('${CO_A}','s1','1','a@x','unsubscribed','2025-01-01','2025-01-01'),
 ('${CO_A}','s2','2','a@x',null,null,'2026-01-01'),
 ('${CO_A}','s1','3','b@x','subscribed','2025-03-01','2025-03-01'),
 ('${CO_A}','s1','4','c@x','not_subscribed','2025-03-01','2025-03-01'),
 ('${CO_A}','s1','5','d@x','subscribed','2025-04-01','2025-04-01'),
 ('${CO_A}','s1','6','e@x',null,null,'2025-04-01'),
 ('${CO_B}','s9','7','a@x','subscribed','2025-05-01','2025-05-01');
`);

const snap = async (co) => (await db.query(`select customer_key, email_consent_state, sms_consent_state, consent_updated_at
  from company_customer_profiles where company_entity_id = '${co}' order by customer_key`)).rows;

// The reference: what the one-statement refresh produces, on a copy.
await db.exec('begin');
await db.query(`select refresh_company_customer_consent('${CO_A}')`);
const expected = await snap(CO_A);
await db.exec('rollback');

// B: step two emails at a time.
const results = [];
for (let i = 0; i < 6; i++) {
  const r = (await db.query(`select refresh_company_customer_consent_step('${CO_A}', 2) as r`)).rows[0].r;
  results.push(r);
  if (r.pass_done) break;
}
assert.equal(results.length, 4, `six emails in steps of two: three full steps, then an empty one ends the pass (got ${results.length})`);
assert.deepEqual(results.map((r) => r.emails), [2, 2, 2, 0], 'each step takes the next two emails');
assert.equal(results.at(-1).pass_done, true, 'the last step says the pass is done');
const state = (await db.query(`select consent_cursor, consent_pass_done_at from company_customer_profile_state where company_entity_id = '${CO_A}'`)).rows[0];
assert.equal(state.consent_cursor, null, 'a finished pass clears the cursor');
assert.ok(state.consent_pass_done_at, 'a finished pass is stamped');

// A + C
assert.deepEqual(await snap(CO_A), expected, 'stepped result equals the one-statement refresh');
const byKey = Object.fromEntries((await snap(CO_A)).map((r) => [r.customer_key, r.email_consent_state]));
assert.equal(byKey['e:a@x'], 'unsubscribed', 'a measured unsubscribe beats a later unmeasured edit');
assert.equal(byKey['e:gone@x'], null, 'an email with no customer record loses its copied consent');
assert.equal(byKey['e:e@x'], null, 'an unmeasured customer stays not measured');

// D
assert.equal((await snap(CO_B))[0].email_consent_state, null, "company B's profile is untouched by A's steps");

// B again: the next step starts a new pass from the first email.
const again = (await db.query(`select refresh_company_customer_consent_step('${CO_A}', 2) as r`)).rows[0].r;
assert.equal(again.emails, 2, 'a new pass starts from the beginning');
assert.equal(again.profiles_updated, 0, 'nothing changed, nothing rewritten');

// E
for (const role of ['anon', 'authenticated']) {
  const ok = (await db.query(`select has_function_privilege('${role}', 'public.refresh_company_customer_consent_step(uuid, integer)', 'execute') as ok`)).rows[0].ok;
  assert.equal(ok, false, `${role} cannot call the step`);
}

console.log(`customer-consent-step-database: all checks passed${MUT ? ` (mutation ${MUT} NOT caught)` : ''}`);
if (MUT) process.exit(1);
