-- Shopify customers: marketing consent as it stands NOW, per customer.
--
-- Blake 2026-11-23: "does silo pull in from the shopify sync 'accepts
-- marketing' column?" -- it did not. shopify_orders carries the customer's
-- id, email and name on each order and nothing about consent, and there was
-- no customer table at all.
--
-- Two things worth writing down before reading the shape below.
--
-- 1. `accepts_marketing` no longer exists in Shopify. It was replaced by
--    emailMarketingConsent (and its SMS sibling), each a STATE plus an
--    opt-in level and the moment consent last changed:
--      SUBSCRIBED | NOT_SUBSCRIBED | PENDING | UNSUBSCRIBED | REDACTED | INVALID
--    So a boolean column would be a lossy translation of the source. The
--    state is stored verbatim, lowercased, and `*_subscribed` is a generated
--    convenience on top of it -- never the other way round.
--
-- 2. Consent is CUSTOMER-level and it changes after the order. Deriving it
--    from the customer embedded in each order would freeze it at the moment
--    of purchase, so an unsubscribe would be invisible for as long as that
--    person did not buy again. This table is therefore fed by its own
--    customers_sync job, which asks Shopify for customers CHANGED since the
--    last run -- and a consent change is such a change, which is the whole
--    reason it stays current.
--
-- Generic: one row per customer per store per company, no company named
-- anywhere, and a store that has not granted read_customers simply has no
-- rows here while everything else it syncs carries on untouched.
--
-- NULL means NOT MEASURED, as everywhere else in SILO: a store whose token
-- cannot read customers, or a customer Shopify has not told us about yet, is
-- not a customer who said no.

-- --------------------------------------------------------------- the table

create table if not exists public.shopify_customers (
  id bigint generated by default as identity primary key,
  company_entity_id uuid not null references public.entities(id) on delete cascade,
  connection_id uuid references public.shopify_connections(id) on delete set null,
  shop_domain text not null,
  customer_id text not null,

  email text,
  -- The join key for anything matching a person across stores or against
  -- company_customer_profiles. Generated, so it cannot drift from `email`.
  email_lc text generated always as (nullif(lower(btrim(email)), '')) stored,
  phone text,
  first_name text,
  last_name text,
  customer_name text,

  -- Shopify's own account state ('enabled' | 'disabled' | 'invited' |
  -- 'declined'). Not consent, and not a substitute for it.
  state text,
  verified_email boolean,
  tags text,

  orders_count integer,
  total_spent numeric,
  currency text,

  -- Consent, verbatim from Shopify, lowercased. See the header: these are
  -- states, not booleans.
  email_consent_state text,
  email_consent_opt_in_level text,
  email_consent_updated_at timestamptz,
  sms_consent_state text,
  sms_consent_opt_in_level text,
  sms_consent_collected_from text,
  sms_consent_updated_at timestamptz,

  -- Convenience for reports and the API, derived so the two can never
  -- disagree. A NULL state stays NULL here: not measured is not "no".
  email_subscribed boolean generated always as (
    case when email_consent_state is null then null
         else email_consent_state = 'subscribed' end
  ) stored,
  sms_subscribed boolean generated always as (
    case when sms_consent_state is null then null
         else sms_consent_state = 'subscribed' end
  ) stored,

  -- Where this person is, which shopify_orders does not carry. The
  -- past-customer matcher's header notes the absence; this closes it for
  -- anyone who wants it later.
  city text,
  province_code text,
  country_code text,

  shopify_created_at timestamptz,
  shopify_updated_at timestamptz,
  synced_at timestamptz,
  sync_batch_id text,
  created_at timestamptz not null default now(),

  -- Per company AND per store from the start: the same person is a separate
  -- customer record in each Shopify store, and a second company syncing the
  -- same store must never move the first company's rows (the 20261013220000
  -- lesson, paid for once already on the order facts).
  unique (company_entity_id, shop_domain, customer_id)
);

comment on table public.shopify_customers is
  'One row per Shopify customer per store per company, with marketing consent as of the last customers_sync. Consent is a STATE, not a boolean; NULL means not measured, never "not subscribed".';
comment on column public.shopify_customers.email_consent_state is
  'Shopify emailMarketingConsent.marketingState, lowercased: subscribed | not_subscribed | pending | unsubscribed | redacted | invalid. NULL = not measured.';

create index if not exists shopify_customers_co_email_idx
  on public.shopify_customers (company_entity_id, email_lc) where email_lc is not null;
create index if not exists shopify_customers_co_email_consent_idx
  on public.shopify_customers (company_entity_id, email_consent_state);
create index if not exists shopify_customers_co_updated_idx
  on public.shopify_customers (company_entity_id, shopify_updated_at desc);
create index if not exists shopify_customers_connection_idx
  on public.shopify_customers (connection_id);

alter table public.shopify_customers enable row level security;

-- Clients read their active company's customers; only the sync
-- (service_role, which bypasses RLS) writes.
drop policy if exists shopify_customers_active_select on public.shopify_customers;
create policy shopify_customers_active_select
  on public.shopify_customers for select to authenticated
  using (company_entity_id = public.active_company_id());

revoke insert, update, delete on public.shopify_customers from authenticated;
grant all on public.shopify_customers to service_role;

-- --------------------------------------------------------------- the view

-- The cleaned read surface: one row per person per company, newest consent
-- across that company's stores. A person subscribed in one store and silent
-- in another is SUBSCRIBED here, because the newest consent event is the one
-- that describes them -- and the store that recorded it is named, so a reader
-- can always get back to the row it came from.
--
-- A MEASURED consent always outranks an unmeasured one, whatever the record's
-- own updated_at. Ranking on coalesce(consent_updated_at, shopify_updated_at)
-- alone (the first version, caught in review) let a store with NULL consent
-- and a later address edit replace another store's explicit unsubscribe with
-- NULL -- and, because the date came from a separate max(), report that NULL
-- next to the unsubscribe's own timestamp. Every field of a channel is now
-- taken from the SAME chosen record, so the state, its level, its date and
-- the store that recorded it always describe one real consent event.
create or replace view public.shopify_customer_consent_v
with (security_invoker = true) as
select
  c.company_entity_id,
  c.email_lc,
  (array_agg(c.customer_name order by c.shopify_updated_at desc nulls last))[1] as customer_name,
  (array_agg(c.phone order by c.shopify_updated_at desc nulls last))[1] as phone,
  (array_agg(c.shop_domain order by (c.email_consent_state is not null) desc, c.email_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as consent_shop_domain,
  (array_agg(c.email_consent_state order by (c.email_consent_state is not null) desc, c.email_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as email_consent_state,
  (array_agg(c.email_consent_opt_in_level order by (c.email_consent_state is not null) desc, c.email_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as email_consent_opt_in_level,
  (array_agg(c.email_consent_updated_at order by (c.email_consent_state is not null) desc, c.email_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as email_consent_updated_at,
  (array_agg(c.sms_consent_state order by (c.sms_consent_state is not null) desc, c.sms_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as sms_consent_state,
  (array_agg(c.sms_consent_opt_in_level order by (c.sms_consent_state is not null) desc, c.sms_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as sms_consent_opt_in_level,
  (array_agg(c.sms_consent_updated_at order by (c.sms_consent_state is not null) desc, c.sms_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as sms_consent_updated_at,
  bool_or(c.email_subscribed) as email_subscribed_anywhere,
  bool_or(c.sms_subscribed) as sms_subscribed_anywhere,
  count(*)::int as store_records,
  sum(coalesce(c.orders_count, 0))::int as orders_count,
  sum(coalesce(c.total_spent, 0)) as total_spent,
  max(c.shopify_updated_at) as shopify_updated_at
from public.shopify_customers c
where c.email_lc is not null
group by c.company_entity_id, c.email_lc;

comment on view public.shopify_customer_consent_v is
  'One row per person (by email) per company: newest marketing consent across that company''s Shopify stores, with the store that recorded it. security_invoker, so RLS applies.';

grant select on public.shopify_customer_consent_v to authenticated;

-- ------------------------------------------- consent on the customer lookup

-- company_customer_profiles is the precomputed past-customer lookup
-- (20261123210000), built from orders. Consent cannot be derived from orders,
-- so it is carried here instead of recomputed -- and it is a SEPARATE
-- function from refresh_company_customer_profiles() on purpose: the orders
-- rollup and the consent rollup have different inputs, different cadences and
-- different failure modes, and a store without read_customers must leave the
-- orders side completely alone.
alter table public.company_customer_profiles
  add column if not exists email_consent_state text,
  add column if not exists sms_consent_state text,
  add column if not exists consent_updated_at timestamptz,
  add column if not exists consent_checked_at timestamptz;

comment on column public.company_customer_profiles.email_consent_state is
  'Copied from shopify_customers by refresh_company_customer_consent(). NULL = not measured (no customers_sync for that store, or no matching customer record) -- never "not subscribed".';

-- Carry consent from shopify_customers onto the lookup, for the customers
-- whose Shopify record changed since p_since (NULL = all of them).
--
-- Matched on email only. A profile keyed 'cid:123' has no email to match on,
-- and guessing across stores by name is exactly the kind of inference that
-- must not drive a marketing-consent field.
create or replace function public.refresh_company_customer_consent(
  p_company uuid,
  p_since   timestamptz default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rows    integer := 0;
  v_cleared integer := 0;
begin
  if p_company is null then
    raise exception 'refresh_company_customer_consent: company is required';
  end if;

  -- The chosen consent event per channel, with a MEASURED state always ahead
  -- of an unmeasured one -- the same rule as shopify_customer_consent_v, and
  -- for the same reason: a store with NULL consent and a later profile edit
  -- must not replace another store's explicit unsubscribe. The date comes from
  -- the chosen events, so it can never describe a different record than the
  -- state does.
  with src as (
    select c.email_lc,
           (array_agg(c.email_consent_state order by (c.email_consent_state is not null) desc, c.email_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as email_consent_state,
           (array_agg(c.email_consent_updated_at order by (c.email_consent_state is not null) desc, c.email_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as email_consent_updated_at,
           (array_agg(c.sms_consent_state order by (c.sms_consent_state is not null) desc, c.sms_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as sms_consent_state,
           (array_agg(c.sms_consent_updated_at order by (c.sms_consent_state is not null) desc, c.sms_consent_updated_at desc nulls last, c.shopify_updated_at desc nulls last))[1] as sms_consent_updated_at
      from public.shopify_customers c
     where c.company_entity_id = p_company
       and c.email_lc is not null
       and (p_since is null or c.synced_at >= p_since or c.shopify_updated_at >= p_since)
     group by c.email_lc
  )
  update public.company_customer_profiles p
     set email_consent_state = src.email_consent_state,
         sms_consent_state   = src.sms_consent_state,
         consent_updated_at  = greatest(src.email_consent_updated_at, src.sms_consent_updated_at),
         consent_checked_at  = now(),
         updated_at          = now()
    from src
   where p.company_entity_id = p_company
     and p.email_lc = src.email_lc
     and (
       p.email_consent_state is distinct from src.email_consent_state
       or p.sms_consent_state is distinct from src.sms_consent_state
       or p.consent_updated_at is distinct from greatest(src.email_consent_updated_at, src.sms_consent_updated_at)
       or p.consent_checked_at is null
     );
  get diagnostics v_rows = row_count;

  -- A FULL refresh also takes consent back OFF a profile whose email no longer
  -- has a customer record behind it. A person who changes their email, or has
  -- it removed, leaves an old-address profile row (built from orders, which
  -- keep the address they were placed with) that the join above can never
  -- touch again -- so without this it would carry "subscribed" for ever,
  -- which is the one direction a consent field must never fail in. Order
  -- totals are untouched; only the copied consent is cleared, back to NULL,
  -- which means not measured.
  if p_since is null then
    update public.company_customer_profiles p
       set email_consent_state = null,
           sms_consent_state   = null,
           consent_updated_at  = null,
           consent_checked_at  = now(),
           updated_at          = now()
     where p.company_entity_id = p_company
       and (p.email_consent_state is not null or p.sms_consent_state is not null)
       and not exists (
         select 1 from public.shopify_customers c
          where c.company_entity_id = p_company
            and c.email_lc is not null
            and c.email_lc = p.email_lc
       );
    get diagnostics v_cleared = row_count;
  end if;

  return jsonb_build_object(
    'company_entity_id', p_company,
    'since', p_since,
    'profiles_updated', v_rows,
    'profiles_cleared', v_cleared
  );
end $$;

revoke all on function public.refresh_company_customer_consent(uuid, timestamptz) from public, anon, authenticated;
grant execute on function public.refresh_company_customer_consent(uuid, timestamptz) to service_role;

